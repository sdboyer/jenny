package jenny_test

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"strings"

	"github.com/sdboyer/jenny"
)

// goSource is a Go file as a syntax tree.
type goSource struct {
	fset *token.FileSet
	file *ast.File
}

func renderGo(g goSource) ([]byte, error) {
	var b bytes.Buffer
	if err := format.Node(&b, g.fset, g.file); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// goTypeTree is goType, building a syntax tree rather than text.
func goTypeTree(r Resource) (jenny.File, error) {
	fields := make([]*ast.Field, 0, len(r.Fields))
	for _, f := range r.Fields {
		t, ok := goFieldTypes[f.Type]
		if !ok {
			return nil, fmt.Errorf("unsupported field type %q", f.Type)
		}
		fields = append(fields, &ast.Field{Names: []*ast.Ident{ast.NewIdent(title(f.Name))}, Type: ast.NewIdent(t)})
	}
	file := &ast.File{
		Name: ast.NewIdent("api"),
		Decls: []ast.Decl{&ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{&ast.TypeSpec{
			Name: ast.NewIdent(title(r.Name)),
			Type: &ast.StructType{Fields: &ast.FieldList{List: fields}},
		}}}},
	}
	return jenny.NewTree(r.Name+".go", goSource{token.NewFileSet(), file}, renderGo), nil
}

// astHeader adds the generated-code comment to a Go syntax tree. It returns a
// new tree rather than changing the one it's given: the new *ast.File shares
// the old one's declarations, but not its comments or package position.
//
// The comment needs a position before the package clause. goTypeTree's trees
// have no positions, so the comment gets a FileSet of its own.
func astHeader(f jenny.File, g goSource) (goSource, error) {
	fset := token.NewFileSet()
	tf := fset.AddFile("", -1, 3)
	tf.SetLines([]int{0, 1, 2}) // the comment, a blank line, the package clause

	file := *g.file
	file.Package = tf.Pos(2)
	file.Comments = append([]*ast.CommentGroup{{List: []*ast.Comment{{
		Slash: tf.Pos(0),
		Text:  "// Code generated by " + f.FromString() + ". DO NOT EDIT.",
	}}}}, g.file.Comments...)
	return goSource{fset, &file}, nil
}

// A Tree carries a file as a value, such as a syntax tree, until something
// needs its bytes. A TreeMapper works on the tree, and the file stays a Tree.
func ExampleTreeMapper() {
	gen := api.New("GoTypes", goTypeTree).Map(jenny.TreeMapper(astHeader))

	fl, err := gen.Generate(resources[0])
	if err != nil {
		panic(err)
	}
	data, _ := fl[0].Render()
	fmt.Printf("%T\n%s", fl[0], data)
	// Output:
	// jenny.Tree[github.com/sdboyer/jenny_test.goSource]
	// // Code generated by GoTypes. DO NOT EDIT.
	//
	// package api
	//
	// type Playlist struct {
	// 	Name     string
	// 	Interval int64
	// }
}

// goHeader adds the generated-code header to every file. A Go file that is
// still a syntax tree gets it in the tree, and stays a tree; any other file
// gets it in its bytes, through the README's header.
func goHeader(f jenny.File) (jenny.File, error) {
	if _, ok := jenny.TreeOf[goSource](f); ok {
		return jenny.TreeMapper(astHeader)(f)
	}
	return header(f)
}

// A FileMapper can ask what kind of file it's given, with jenny.TreeOf and
// jenny.BytesOf, to keep a syntax tree where there is one and work on bytes
// where there isn't. Never a type switch or a type assertion: see jenny.File.
func ExampleFileMapper() {
	gen := jenny.Map(goHeader,
		api.New("GoTypes", goTypeTree),
		api.New("Routes", routes),
	)

	fl, err := gen.Generate(resources[0])
	if err != nil {
		panic(err)
	}
	for _, f := range fl {
		data, _ := f.Render()
		first, _, _ := bytes.Cut(data, []byte("\n"))
		fmt.Printf("%s: %T\n\t%s\n", f.Path(), f, first)
	}
	// Output:
	// playlist.go: jenny.Tree[github.com/sdboyer/jenny_test.goSource]
	// 	// Code generated by GoTypes. DO NOT EDIT.
	// routes.go: jenny.Bytes
	// 	// Code generated by Routes. DO NOT EDIT.
}

// tsModule is a TypeScript module as a minimal syntax tree: leading comments,
// then exported string constants. It stands in for whatever AST package a
// generator uses for its target language, Go or not. A Tree needs only a value
// and a func that renders it, so a CUE ast.File rendered by cue/format, or a
// tree of your own like this one, works the same way as a go/ast tree.
type tsModule struct {
	Comments []string // without the leading "//"
	Consts   []tsConst
}

// tsConst is `export const Name = "Value";`.
type tsConst struct{ Name, Value string }

func renderTS(m tsModule) ([]byte, error) {
	var b strings.Builder
	for _, c := range m.Comments {
		fmt.Fprintf(&b, "//%s\n", c)
	}
	if len(m.Comments) != 0 {
		b.WriteString("\n")
	}
	for _, c := range m.Consts {
		fmt.Fprintf(&b, "export const %s = %q;\n", c.Name, c.Value)
	}
	return []byte(b.String()), nil
}

// tsPathsTree is the README's tsPaths, building a syntax tree rather than
// text.
func tsPathsTree(v Version) (jenny.File, error) {
	m := tsModule{Consts: []tsConst{{"path", fmt.Sprintf("/api/v%d/%s", v.N, v.Resource.Name)}}}
	return jenny.NewTree(fmt.Sprintf("%s/v%d.ts", v.Resource.Name, v.N), m, renderTS), nil
}

// tsHeader adds the generated-code comment to a TypeScript tree. Like
// astHeader, it returns a new value: m is a copy, and the new Comments slice
// leaves the old one untouched.
func tsHeader(f jenny.File, m tsModule) (tsModule, error) {
	m.Comments = append([]string{" Code generated by " + f.FromString() + ". DO NOT EDIT."}, m.Comments...)
	return m, nil
}

// Trees aren't only Go. Here Go files travel as go/ast trees and TypeScript
// files as tsModule trees, side by side. Each TreeMapper works on the trees of
// its own type and passes every other file through.
func ExampleTreeMapper_typeScript() {
	gen := jenny.Pipeline(
		api.New("GoTypes", goTypeTree),
		api.Adapt(versions, ver.New("TSPaths", tsPathsTree)),
	).Map(jenny.TreeMapper(astHeader)).Map(jenny.TreeMapper(tsHeader))

	fl, err := gen.Generate(resources[0])
	if err != nil {
		panic(err)
	}
	for _, f := range fl {
		data, _ := f.Render()
		fmt.Printf("== %s: %T\n%s", f.Path(), f, data)
	}
	// Output:
	// == playlist.go: jenny.Tree[github.com/sdboyer/jenny_test.goSource]
	// // Code generated by GoTypes. DO NOT EDIT.
	//
	// package api
	//
	// type Playlist struct {
	// 	Name     string
	// 	Interval int64
	// }
	// == playlist/v1.ts: jenny.Tree[github.com/sdboyer/jenny_test.tsModule]
	// // Code generated by TSPaths. DO NOT EDIT.
	//
	// export const path = "/api/v1/playlist";
	// == playlist/v2.ts: jenny.Tree[github.com/sdboyer/jenny_test.tsModule]
	// // Code generated by TSPaths. DO NOT EDIT.
	//
	// export const path = "/api/v2/playlist";
}
