func TestFSClaims(t *testing.T) {
	j := jenny.Pipeline(
		goTypesOwning("GoTypes").Prefix("pkg"),
		owner("pkg/*.go"), // another jenny's identical pattern: kept
	)
	jfs, err := j.GenerateFS(ab[0])
	if err != nil {
		t.Fatal(err)
	}
	// Re-adding an identical claim (pattern and jennies) has no effect.
	again, err := goTypesOwning("GoTypes").Prefix("pkg").GenerateFS()
	if err != nil {
		t.Fatal(err)
	}
	if err := jfs.Merge(again); err != nil {
		t.Fatal(err)
	}

	want := []string{"pkg/*.go (GoTypes)", "pkg/*.go (Owner)"}
	if diff := cmp.Diff(want, claimPaths(jfs.Claims())); diff != "" {
		t.Errorf("Claims (-want +got):\n%s", diff)
	}
	if diff := cmp.Diff([]string{"pkg/a.go"}, paths(jfs.AsFiles())); diff != "" {
		t.Errorf("AsFiles holds only files (-want +got):\n%s", diff)
	}
	if jfs.Len() != 1 {
		t.Errorf("Len is %d, want 1: claims aren't files", jfs.Len())
	}

	// Claims are invisible through io/fs.
	if err := fstest.TestFS(jfs, "pkg/a.go"); err != nil {
		t.Error(err)
	}
	if m, _ := fs.Glob(jfs, "pkg/*"); len(m) != 1 {
		t.Errorf("Glob found %v, want only pkg/a.go", m)
	}

	merged := jenny.NewFS()
	if err := merged.Merge(jfs); err != nil {
		t.Fatal(err)
	}
	mapped, err := merged.Map(jenny.BytesMapper(func(_ jenny.File, b []byte) ([]byte, error) { return b, nil }))
	if err != nil {
		t.Fatal(err)
	}
	if diff := cmp.Diff(want, claimPaths(mapped.Claims())); diff != "" {
		t.Errorf("Merge and Map lost claims (-want +got):\n%s", diff)
	}
}

// staleFixture is an FS holding the output of two jennies sharing pkg/api,
// one of which claims every .go file there.
func staleFixture(t *testing.T) *jenny.FS {
	t.Helper()
	j := jenny.Prefix("pkg/api",
		goTypesOwning("GoTypes"),
		ty.New("Routes", func(...Type) (jenny.File, error) { return jenny.NewFile("routes.go", nil), nil }),
	)
	jfs, err := j.GenerateFS(ab...)
	if err != nil {
		t.Fatal(err)
	}
	return jfs
}

func TestStale(t *testing.T) {
	disk := fstest.MapFS{
		"pkg/api/a.go":        {}, // generated
		"pkg/api/B.go":        {}, // generated as b.go; differs only by case
		"pkg/api/routes.go":   {}, // generated by Routes, inside GoTypes' claim
		"pkg/api/old.go":      {}, // stale
		"pkg/api/Older.GO":    {}, // stale, matched case-insensitively
		"pkg/api/README.md":   {}, // not claimed
		"pkg/api/sub/x.go":    {}, // deeper than the claim reaches
		"pkg/other/x.go":      {}, // outside the claim
		"pkg/api.go":          {}, // outside the claim
		"pkg/api/dir.go/x":    {}, // a directory matching the claim isn't a file
		"pkg/apiary/stale.go": {},
	}
	got, err := staleFixture(t).Stale(context.Background(), disk)
	if err != nil {
		t.Fatal(err)
	}
	if diff := cmp.Diff([]string{"pkg/api/Older.GO", "pkg/api/old.go"}, got); diff != "" {
		t.Errorf("(-want +got):\n%s", diff)
	}

	t.Run("claim dir missing on disk", func(t *testing.T) {
		got, err := staleFixture(t).Stale(context.Background(), fstest.MapFS{"x.go": {}})
		if err != nil || len(got) != 0 {
			t.Errorf("got %v, %v; want nothing", got, err)
		}
	})

	t.Run("pattern depth", func(t *testing.T) {
		jfs, err := owner("gen/*/types.go").GenerateFS()
		if err != nil {
			t.Fatal(err)
		}
		got, err := jfs.Stale(context.Background(), fstest.MapFS{
			"gen/v1/types.go":   {},
			"gen/v1/x/types.go": {},
			"gen/types.go":      {},
		})
		if err != nil {
			t.Fatal(err)
		}
		if diff := cmp.Diff([]string{"gen/v1/types.go"}, got); diff != "" {
			t.Errorf("(-want +got):\n%s", diff)
		}
	})

	t.Run("canceled", func(t *testing.T) {
		ctx, cancel := context.WithCancel(context.Background())
		cancel()
		if _, err := staleFixture(t).Stale(ctx, disk); !errors.Is(err, context.Canceled) {
			t.Errorf("got %v, want context.Canceled", err)
		}
	})
}

// Stale and Verify on a real directory, through os.DirFS, on every OS CI runs.
func TestVerifyReportsStale(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	jfs := staleFixture(t)
	if err := jfs.Write(ctx, dir); err != nil {
		t.Fatal(err)
	}
	if err := jfs.Verify(ctx, dir); err != nil {
		t.Fatalf("Verify after Write: %s", err)
	}

	for _, name := range []string{"old.go", "README.md"} {
		if err := os.WriteFile(filepath.Join(dir, "pkg", "api", name), nil, 0o600); err != nil {
			t.Fatal(err)
		}
	}

	got, err := jfs.Stale(ctx, os.DirFS(dir))
	if err != nil {
		t.Fatal(err)
	}
	if diff := cmp.Diff([]string{"pkg/api/old.go"}, got); diff != "" {
		t.Errorf("Stale (-want +got):\n%s", diff)
	}

	err = jfs.Verify(ctx, dir)
	if err == nil {
		t.Fatal("expected Verify to report the stale file")
	}
	want := `pkg/api/old.go: stale: matches claim pkg/api/*.go of jenny "GoTypes", but was not generated`
	if err.Error() != want {
		t.Errorf("Verify error is\n%s\nwant\n%s", err, want)
	}
	if strings.Contains(err.Error(), "README") {
		t.Error("Verify reported an unclaimed file")
	}
}

// Stale files are *StaleErrors, after the *DriftErrors, in one flat join.
func TestVerifyFSStaleErrors(t *testing.T) {
	persisted := fstest.MapFS{
		"pkg/api/a.go":      {Data: []byte("changed")}, // differs
		"pkg/api/routes.go": {},                        // matches
		"pkg/api/old.go":    {},                        // stale
		// pkg/api/b.go is missing
	}
	err := staleFixture(t).VerifyFS(context.Background(), persisted)
	joined, ok := err.(interface{ Unwrap() []error }) //nolint:errorlint // inspecting the join itself
	if !ok {
		t.Fatalf("VerifyFS returned %T, want a join: %v", err, err)
	}
	var got []string
	for _, e := range joined.Unwrap() {
		var (
			de *jenny.DriftError
			se *jenny.StaleError
		)
		switch {
		case errors.As(e, &de):
			got = append(got, "drift "+de.Path)
		case errors.As(e, &se):
			got = append(got, "stale "+se.Path+" "+se.Claim.Path()+" "+se.Claim.FromString())
		default:
			t.Fatalf("joined error %T is neither a DriftError nor a StaleError: %v", e, e)
		}
	}
	want := []string{"drift pkg/api/a.go", "drift pkg/api/b.go", "stale pkg/api/old.go pkg/api/*.go GoTypes"}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("(-want +got):\n%s", diff)
	}
}
