func TestFSClaims(t *testing.T) {
	jfs := fsWith(t,
		jenny.NewFile("pkg/a.go", []byte("a"), src("GoTypes")),
		jenny.NewClaim("pkg/*.go", src("GoTypes")),
		jenny.NewClaim("pkg/*.go", src("GoTypes")), // identical: kept once
		jenny.NewClaim("pkg/*.go", src("Other")),   // another jenny's: kept
	)
	if err := jfs.Add(jenny.NewClaim("pkg/*.go", src("GoTypes"))); err != nil {
		t.Errorf("re-adding an identical claim failed: %s", err)
	}

	want := []string{"pkg/*.go (GoTypes)", "pkg/*.go (Other)", "pkg/a.go (GoTypes)"}
	got := make([]string, 0)
	for _, f := range jfs.AsFiles() {
		got = append(got, f.Path()+" ("+f.FromString()+")")
	}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("AsFiles (-want +got):\n%s", diff)
	}
	if jfs.Len() != 1 {
		t.Errorf("Len is %d, want 1: claims aren't files", jfs.Len())
	}

	// Claims are invisible through io/fs.
	if err := fstest.TestFS(jfs, "pkg/a.go"); err != nil {
		t.Error(err)
	}
	if m, _ := fs.Glob(jfs, "pkg/*"); len(m) != 1 {
		t.Errorf("Glob found %v, want only pkg/a.go", m)
	}

	merged := jenny.NewFS()
	if err := merged.Merge(jfs); err != nil {
		t.Fatal(err)
	}
	mapped, err := merged.Map(jenny.BytesMapper(func(_ jenny.File, b []byte) ([]byte, error) { return b, nil }))
	if err != nil {
		t.Fatal(err)
	}
	if diff := cmp.Diff(paths(jfs.AsFiles()), paths(mapped.AsFiles())); diff != "" {
		t.Errorf("Merge and Map lost claims (-want +got):\n%s", diff)
	}
}

