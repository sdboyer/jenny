func TestStale(t *testing.T) {
	disk := fstest.MapFS{
		"pkg/api/a.go":        {}, // generated
		"pkg/api/B.go":        {}, // generated as b.go; differs only by case
		"pkg/api/routes.go":   {}, // generated by Routes, inside GoTypes' claim
		"pkg/api/old.go":      {}, // stale
		"pkg/api/Older.GO":    {}, // stale, matched case-insensitively
		"pkg/api/README.md":   {}, // not claimed
		"pkg/api/sub/x.go":    {}, // deeper than the claim reaches
		"pkg/other/x.go":      {}, // outside the claim
		"pkg/api.go":          {}, // outside the claim
		"pkg/api/dir.go/x":    {}, // a directory matching the claim isn't a file
		"pkg/apiary/stale.go": {},
	}
	got, err := staleFixture(t).Stale(context.Background(), disk)
	if err != nil {
		t.Fatal(err)
	}
	if diff := cmp.Diff([]string{"pkg/api/Older.GO", "pkg/api/old.go"}, got); diff != "" {
		t.Errorf("(-want +got):\n%s", diff)
	}

	t.Run("claim dir missing on disk", func(t *testing.T) {
		got, err := staleFixture(t).Stale(context.Background(), fstest.MapFS{"x.go": {}})
		if err != nil || len(got) != 0 {
			t.Errorf("got %v, %v; want nothing", got, err)
		}
	})

	t.Run("pattern depth", func(t *testing.T) {
		jfs := fsWith(t, jenny.NewClaim("gen/*/types.go", src("t")))
		got, err := jfs.Stale(context.Background(), fstest.MapFS{
			"gen/v1/types.go":   {},
			"gen/v1/x/types.go": {},
			"gen/types.go":      {},
		})
		if err != nil {
			t.Fatal(err)
		}
		if diff := cmp.Diff([]string{"gen/v1/types.go"}, got); diff != "" {
			t.Errorf("(-want +got):\n%s", diff)
		}
	})

	t.Run("canceled", func(t *testing.T) {
		ctx, cancel := context.WithCancel(context.Background())
		cancel()
		if _, err := staleFixture(t).Stale(ctx, disk); !errors.Is(err, context.Canceled) {
			t.Errorf("got %v, want context.Canceled", err)
		}
	})
}

// Stale and Verify on a real directory, through os.DirFS, on every OS CI runs.
func TestVerifyReportsStale(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	jfs := staleFixture(t)
	if err := jfs.Write(ctx, dir); err != nil {
		t.Fatal(err)
	}
	if err := jfs.Verify(ctx, dir); err != nil {
		t.Fatalf("Verify after Write: %s", err)
	}

	for _, name := range []string{"old.go", "README.md"} {
		if err := os.WriteFile(filepath.Join(dir, "pkg", "api", name), nil, 0o600); err != nil {
			t.Fatal(err)
		}
	}

	got, err := jfs.Stale(ctx, os.DirFS(dir))
	if err != nil {
		t.Fatal(err)
	}
	if diff := cmp.Diff([]string{"pkg/api/old.go"}, got); diff != "" {
		t.Errorf("Stale (-want +got):\n%s", diff)
	}

	err = jfs.Verify(ctx, dir)
	if err == nil {
		t.Fatal("expected Verify to report the stale file")
	}
	want := filepath.Join(dir, "pkg", "api", "old.go") + `: stale: matches claim pkg/api/*.go of jenny "GoTypes", but was not generated`
	if err.Error() != want {
		t.Errorf("Verify error is\n%s\nwant\n%s", err, want)
	}
	if strings.Contains(err.Error(), "README") {
		t.Error("Verify reported an unclaimed file")
	}
}
