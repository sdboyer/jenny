package jenny_test

import (
	"fmt"
	"strings"

	"github.com/sdboyer/jenny"
)

// Kind and SchemaForGen stand in for the types in grafana's core kinds code
// generator, circa grafana v10.0.0.
type Kind struct {
	MachineName string
	Stable      bool
	Majors      []int
}

type SchemaForGen struct {
	Kind  Kind
	Major int // -1 for the unstable "x" schema
}

func (s SchemaForGen) dir() string {
	if s.Major < 0 {
		return s.Kind.MachineName + "/x"
	}
	return fmt.Sprintf("%s/v%d", s.Kind.MachineName, s.Major)
}

// latestMajorsOrX replaces grafana's LatestMajorsOrXJenny. That was a 70-line
// wrapper jenny that also had to call its inner jenny, wrap its errors, check
// for nil output, rewrite paths, and maintain File.From. Now it only converts
// the input.
func latestMajorsOrX(k Kind) ([]SchemaForGen, error) {
	if !k.Stable {
		return []SchemaForGen{{Kind: k, Major: -1}}, nil
	}
	sfgs := make([]SchemaForGen, 0, len(k.Majors))
	for _, m := range k.Majors {
		sfgs = append(sfgs, SchemaForGen{Kind: k, Major: m})
	}
	return sfgs, nil
}

func goTypes(k Kind) (*jenny.File, error) {
	return jenny.NewFile(k.MachineName+"/types_gen.go", nil), nil
}

func baseRegistry(ks ...Kind) (*jenny.File, error) {
	return jenny.NewFile("registry_gen.go", nil), nil
}

func tsTypes(s SchemaForGen) (*jenny.File, error) {
	return jenny.NewFile(s.dir()+"/types.gen.ts", nil), nil
}

func tsVeneerIndex(ks ...Kind) (*jenny.File, error) {
	return jenny.NewFile("index.gen.ts", nil), nil
}

func slashHeader(gen string) jenny.FileMapper {
	return func(f jenny.File) (jenny.File, error) {
		f.Data = append([]byte(fmt.Sprintf("// generated by %s using %s\n", gen, f.FromString())), f.Data...)
		return f, nil
	}
}

func Example() {
	kind := jenny.For[Kind](jenny.InputName(func(k Kind) string { return k.MachineName }))
	sfg := jenny.For[SchemaForGen]()

	coreKindsGen := jenny.Map(slashHeader("kinds/gen.go"),
		kind.New("GoTypes", goTypes).Prefix("pkg/kinds"),
		kind.New("BaseCoreRegistry", baseRegistry).Prefix("pkg/registry/corekind"),
		kind.Adapt(latestMajorsOrX,
			sfg.New("TSTypes", tsTypes),
		).Prefix("packages/grafana-schema/src/raw"),
		kind.New("TSVeneerIndex", tsVeneerIndex).Prefix("packages/grafana-schema/src"),
	)

	fs, err := coreKindsGen.GenerateFS(
		Kind{MachineName: "dashboard", Stable: true, Majors: []int{0, 1}},
		Kind{MachineName: "playlist"},
	)
	if err != nil {
		panic(err)
	}
	for _, f := range fs.AsFiles() {
		fmt.Printf("%s\n\t%s", f.RelativePath, strings.SplitAfter(string(f.Data), "\n")[0])
	}
	// Output:
	// packages/grafana-schema/src/index.gen.ts
	// 	// generated by kinds/gen.go using TSVeneerIndex
	// packages/grafana-schema/src/raw/dashboard/v0/types.gen.ts
	// 	// generated by kinds/gen.go using TSTypes
	// packages/grafana-schema/src/raw/dashboard/v1/types.gen.ts
	// 	// generated by kinds/gen.go using TSTypes
	// packages/grafana-schema/src/raw/playlist/x/types.gen.ts
	// 	// generated by kinds/gen.go using TSTypes
	// pkg/kinds/dashboard/types_gen.go
	// 	// generated by kinds/gen.go using GoTypes
	// pkg/kinds/playlist/types_gen.go
	// 	// generated by kinds/gen.go using GoTypes
	// pkg/registry/corekind/registry_gen.go
	// 	// generated by kinds/gen.go using BaseCoreRegistry
}
