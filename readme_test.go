package jenny_test

// The examples in this file are the README walkthrough. Keep them in sync.

import (
	"context"
	"errors"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/sdboyer/jenny"
)

type Field struct {
	Name, Type string
}

// Resource is one resource in an API definition.
type Resource struct {
	Name     string
	Fields   []Field
	Versions []int // API versions that serve this resource
}

// Version is one API version of a Resource.
type Version struct {
	Resource Resource
	N        int
}

var resources = []Resource{
	{Name: "playlist", Fields: []Field{{"name", "string"}, {"interval", "int"}}, Versions: []int{1, 2}},
	{Name: "team", Fields: []Field{{"name", "string"}, {"email", "string"}}, Versions: []int{1}},
}

var (
	api = jenny.For[Resource](jenny.InputName(func(r Resource) string { return r.Name }))
	ver = jenny.For[Version](jenny.InputName(func(v Version) string { return fmt.Sprintf("%s/v%d", v.Resource.Name, v.N) }))
)

func title(s string) string { return strings.ToUpper(s[:1]) + s[1:] }

var goFieldTypes = map[string]string{"string": "string", "int": "int64"}

func goType(r Resource) (jenny.File, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "package api\n\ntype %s struct {\n", title(r.Name))
	for _, f := range r.Fields {
		t, ok := goFieldTypes[f.Type]
		if !ok {
			return nil, fmt.Errorf("unsupported field type %q", f.Type)
		}
		fmt.Fprintf(&b, "\t%s %s\n", title(f.Name), t)
	}
	b.WriteString("}\n")
	return jenny.NewFile(r.Name+".go", []byte(b.String())), nil
}

func routes(rs ...Resource) (jenny.File, error) {
	var b strings.Builder
	b.WriteString("package api\n\nvar Routes = map[string]any{\n")
	for _, r := range rs {
		fmt.Fprintf(&b, "\t%q: %s{},\n", "/"+r.Name, title(r.Name))
	}
	b.WriteString("}\n")
	return jenny.NewFile("routes.go", []byte(b.String())), nil
}

func versions(r Resource) ([]Version, error) {
	vs := make([]Version, 0, len(r.Versions))
	for _, n := range r.Versions {
		vs = append(vs, Version{Resource: r, N: n})
	}
	return vs, nil
}

func tsPaths(v Version) (jenny.File, error) {
	data := fmt.Sprintf("export const path = %q;\n", fmt.Sprintf("/api/v%d/%s", v.N, v.Resource.Name))
	return jenny.NewFile(fmt.Sprintf("%s/v%d.ts", v.Resource.Name, v.N), []byte(data)), nil
}

func tsIndex(vs ...Version) (jenny.File, error) {
	var b strings.Builder
	for _, v := range vs {
		fmt.Fprintf(&b, "export * as v%d from \"./v%d\";\n", v.N, v.N)
	}
	return jenny.NewFile(vs[0].Resource.Name+"/index.ts", []byte(b.String())), nil
}

var gofmt = jenny.BytesMapper(func(_ jenny.File, src []byte) ([]byte, error) {
	return format.Source(src)
})

var header = jenny.BytesMapper(func(f jenny.File, src []byte) ([]byte, error) {
	return append(fmt.Appendf(nil, "// Code generated by %s. DO NOT EDIT.\n\n", f.FromString()), src...), nil
})

func listFiles(fl jenny.Files, err error) {
	if err != nil {
		fmt.Println(err)
		return
	}
	sort.Slice(fl, func(i, j int) bool { return fl[i].Path() < fl[j].Path() })
	for _, f := range fl {
		fmt.Printf("%s (%s)\n", f.Path(), f.FromString())
	}
}

func Example_readmeGenerator() {
	goTypes := api.New("GoTypes", goType)

	listFiles(goTypes.Generate(resources...))

	invoice := Resource{Name: "invoice", Fields: []Field{{"total", "decimal"}}}
	listFiles(goTypes.Generate(append(resources, invoice)...))
	// Output:
	// playlist.go (GoTypes)
	// team.go (GoTypes)
	// GoTypes: unsupported field type "decimal" for input "invoice"
}

func Example_readmeManyInputs() {
	fl, _ := api.New("Routes", routes).Generate(resources...)
	fmt.Print(string(fl[0].(jenny.Bytes).Data()))
	// Output:
	// package api
	//
	// var Routes = map[string]any{
	// 	"/playlist": Playlist{},
	// 	"/team": Team{},
	// }
}

func Example_readmePipeline() {
	gen := jenny.Pipeline(
		api.New("GoTypes", goType),
		api.New("Routes", routes),
	)
	listFiles(gen.Generate(resources...))

	clash := jenny.Pipeline(
		api.New("GoTypes", goType),
		api.New("Bundle", func(...Resource) (jenny.File, error) { return jenny.NewFile("playlist.go", nil), nil }),
	)
	listFiles(clash.Generate(resources...))
	// Output:
	// playlist.go (GoTypes)
	// routes.go (Routes)
	// team.go (GoTypes)
	// multiple files at path playlist.go from jennies: 'GoTypes', 'Bundle'
}

func Example_readmeDecorate() {
	gen := jenny.Map(header,
		jenny.Prefix("pkg/api",
			api.New("GoTypes", goType),
			api.New("Routes", routes),
		).Map(gofmt),
	)
	fl, _ := gen.Generate(resources...)
	listFiles(fl, nil)
	fmt.Print(string(fl[0].(jenny.Bytes).Data()))
	// Output:
	// pkg/api/playlist.go (GoTypes)
	// pkg/api/routes.go (Routes)
	// pkg/api/team.go (GoTypes)
	// // Code generated by GoTypes. DO NOT EDIT.
	//
	// package api
	//
	// type Playlist struct {
	// 	Name     string
	// 	Interval int64
	// }
}

func Example_readmeAdapt() {
	gen := api.Adapt(versions,
		ver.New("TSPaths", tsPaths),
		ver.New("TSIndex", tsIndex),
	).Prefix("web/src/api")

	fl, _ := gen.Generate(resources...)
	listFiles(fl, nil)
	fmt.Print(string(fl[0].(jenny.Bytes).Data()))
	// Output:
	// web/src/api/playlist/index.ts (TSIndex)
	// web/src/api/playlist/v1.ts (TSPaths)
	// web/src/api/playlist/v2.ts (TSPaths)
	// web/src/api/team/index.ts (TSIndex)
	// web/src/api/team/v1.ts (TSPaths)
	// export * as v1 from "./v1";
	// export * as v2 from "./v2";
}

func Example_readme() {
	gen := jenny.Map(header,
		jenny.Prefix("pkg/api",
			api.New("GoTypes", goType),
			api.New("Routes", routes),
		).Map(gofmt),
		api.Adapt(versions,
			ver.New("TSPaths", tsPaths),
			ver.New("TSIndex", tsIndex),
		).Prefix("web/src/api"),
	)
	listFiles(gen.Generate(resources...))
	// Output:
	// pkg/api/playlist.go (GoTypes)
	// pkg/api/routes.go (Routes)
	// pkg/api/team.go (GoTypes)
	// web/src/api/playlist/index.ts (TSIndex)
	// web/src/api/playlist/v1.ts (TSPaths)
	// web/src/api/playlist/v2.ts (TSPaths)
	// web/src/api/team/index.ts (TSIndex)
	// web/src/api/team/v1.ts (TSPaths)
}

func Example_readmeClaim() {
	gen := jenny.Prefix("pkg/api",
		api.New("GoTypes", goType, jenny.Owns("*.go")),
		api.New("Routes", routes),
	)

	root, _ := os.MkdirTemp("", "jenny-readme")
	defer os.RemoveAll(root)
	ctx := context.Background()

	all, _ := gen.GenerateFS(resources...)
	_ = all.Write(ctx, root)

	// team is no longer an input.
	fs, _ := gen.GenerateFS(resources[0])
	err := fs.Verify(ctx, root)
	// Verify also reports that routes.go changed; print only stale files.
	var stale *jenny.StaleError
	if errors.As(err, &stale) {
		fmt.Println(stale)
	}
	// Output:
	// pkg/api/team.go: stale: matches claim pkg/api/*.go of jenny "GoTypes", but was not generated
}
