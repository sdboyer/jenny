package jenny

import (
	"runtime"
	"strings"
	"sync"
)

// NamedJenny is a named element of a [File.From] stack.
//
// Only this package makes NamedJennies: [Builder.New] for the jennies it
// makes, and [Name] for Files built by hand.
type NamedJenny interface {
	// JennyName is the name given to the jenny.
	JennyName() string
	// JennyPackage is the import path of the package that named the jenny.
	// See [Builder.New] for how it's determined.
	JennyPackage() string

	namedJenny()
}

type namedJenny struct {
	name, pkg string
}

func (n namedJenny) JennyName() string    { return n.name }
func (n namedJenny) JennyPackage() string { return n.pkg }
func (namedJenny) namedJenny()            {}

// Equal reports whether n and o have the same name and package. It lets
// github.com/google/go-cmp compare Files without access to unexported fields.
func (n namedJenny) Equal(o NamedJenny) bool {
	return o != nil && n.name == o.JennyName() && n.pkg == o.JennyPackage()
}

// Name returns a NamedJenny for Files that are built by hand, rather than
// generated by a jenny made with [Builder.New]. Its package is that of the
// caller, determined as by New.
func Name(name string) NamedJenny {
	return namedJenny{name: name, pkg: callerPackage()}
}

// helpers holds the names of funcs that have called [Helper]. Like the set
// behind testing.T.Helper, it's process-wide: being a helper is a property of
// a func, not of any one Builder.
var helpers sync.Map //nolint:gochecknoglobals // see above

// Helper marks the calling func as a jenny helper. When [Builder.New] or
// [Name] determines the package of a jenny's caller, it skips helper funcs, so
// that a jenny made through a helper defined in another package is attributed
// to the package that called the helper. It works like [testing.T.Helper].
func Helper() {
	var pcs [1]uintptr
	if runtime.Callers(2, pcs[:]) == 0 {
		return
	}
	frame, _ := runtime.CallersFrames(pcs[:]).Next()
	helpers.Store(frame.Function, struct{}{})
}

// selfPackage is the import path of this package. It's derived rather than
// hard-coded, so that it survives a module rename.
var selfPackage = func() string { //nolint:gochecknoglobals // computed once
	var pcs [1]uintptr
	runtime.Callers(1, pcs[:])
	frame, _ := runtime.CallersFrames(pcs[:]).Next()
	return funcPackage(frame.Function)
}()

// callerPackage returns the package of the first func on the stack that is
// neither in this package nor a [Helper].
func callerPackage() string {
	var pcs [32]uintptr
	n := runtime.Callers(2, pcs[:])
	frames := runtime.CallersFrames(pcs[:n])
	for {
		frame, more := frames.Next()
		if pkg := funcPackage(frame.Function); pkg != selfPackage {
			if _, helper := helpers.Load(frame.Function); !helper {
				return pkg
			}
		}
		if !more {
			return ""
		}
	}
}

// funcPackage returns the package import path from a fully qualified func
// name, as reported by the runtime: everything up to the first dot after the
// last slash.
//
// This is a heuristic. The runtime doesn't separate the package path from the
// rest of the name, so an import path whose last element contains a dot, such
// as gopkg.in/yaml.v3, is cut short at that dot. [Builder.Namespace] overrides
// it.
func funcPackage(fn string) string {
	slash := strings.LastIndexByte(fn, '/')
	dot := strings.IndexByte(fn[slash+1:], '.')
	if dot < 0 {
		return fn
	}
	return fn[:slash+1+dot]
}
